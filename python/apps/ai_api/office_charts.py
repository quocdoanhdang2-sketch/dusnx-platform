"""Build a native PowerPoint chart slide from explicit user-supplied data.

Office.js has no chart API, so the add-in inserts a one-slide presentation
built here. Values come only from the caller's rows; nothing is generated by
a model, and the result is a real editable chart, not an image.
"""
from __future__ import annotations

import math
from io import BytesIO

from pptx import Presentation
from pptx.chart.data import CategoryChartData
from pptx.dml.color import RGBColor
from pptx.enum.chart import XL_CHART_TYPE, XL_LABEL_POSITION, XL_LEGEND_POSITION
from pptx.enum.shapes import MSO_SHAPE
from pptx.util import Emu, Inches, Pt

MAX_TITLE = 120
MIN_POINTS = 2
MAX_POINTS = 12
MAX_LABEL = 60
MAX_ABS_VALUE = 1e12

CHART_TYPES = {
    "bar": XL_CHART_TYPE.COLUMN_CLUSTERED,
    "line": XL_CHART_TYPE.LINE_MARKERS,
    "pie": XL_CHART_TYPE.PIE,
}
ACCENT = RGBColor(0x25, 0x63, 0xEB)
INK = RGBColor(0x17, 0x20, 0x33)
MUTED = RGBColor(0x5B, 0x66, 0x7A)
PIE_COLORS = [RGBColor(*rgb) for rgb in (
    (0x25, 0x63, 0xEB), (0x0F, 0x76, 0x6E), (0xD9, 0x77, 0x06),
    (0x7C, 0x3A, 0xED), (0xDC, 0x26, 0x26), (0x08, 0x91, 0xB2),
    (0xCA, 0x8A, 0x04), (0x4F, 0x46, 0xE5), (0x15, 0x80, 0x3D),
    (0xBE, 0x18, 0x5D), (0x47, 0x55, 0x69), (0x0E, 0x74, 0x90),
)]


def _text(value, label, limit):
    if not isinstance(value, str):
        raise ValueError(f"{label} must be text.")
    text = value.strip()
    if not text or len(text) > limit:
        raise ValueError(f"{label} must be 1-{limit} characters.")
    if any(ord(char) < 32 or ord(char) == 127 for char in text):
        raise ValueError(f"{label} contains control characters.")
    return text


def validate_chart_request(title, chart_type, labels, values):
    """Return normalized (title, chart_type, labels, values) or raise ValueError."""
    title = _text(title, "Chart title", MAX_TITLE)
    chart_type = str(chart_type or "bar").strip().lower()
    if chart_type not in CHART_TYPES:
        raise ValueError(f"Chart type must be one of: {', '.join(sorted(CHART_TYPES))}.")
    if not isinstance(labels, list) or not MIN_POINTS <= len(labels) <= MAX_POINTS:
        raise ValueError(f"Provide {MIN_POINTS}-{MAX_POINTS} data rows.")
    if not isinstance(values, list) or len(values) != len(labels):
        raise ValueError("Every data row needs exactly one number.")
    normalized_labels, normalized_values = [], []
    for index, (raw_label, raw_value) in enumerate(zip(labels, values), start=1):
        normalized_labels.append(_text(raw_label, f"Label {index}", MAX_LABEL))
        if isinstance(raw_value, bool) or not isinstance(raw_value, (int, float)):
            raise ValueError(f"Value {index} must be a number.")
        value = float(raw_value)
        if not math.isfinite(value) or abs(value) > MAX_ABS_VALUE:
            raise ValueError(f"Value {index} must be a finite number within ±{MAX_ABS_VALUE:g}.")
        normalized_values.append(value)
    return title, chart_type, normalized_labels, normalized_values


def build_chart_slide(title, chart_type, labels, values) -> bytes:
    """Render one 16:9 slide with a native, editable chart and return PPTX bytes."""
    title, chart_type, labels, values = validate_chart_request(title, chart_type, labels, values)
    presentation = Presentation()
    presentation.slide_width = Emu(12192000)
    presentation.slide_height = Emu(6858000)
    slide = presentation.slides.add_slide(presentation.slide_layouts[6])

    accent = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0.45), Inches(0.45), Inches(0.12), Inches(0.62))
    accent.fill.solid()
    accent.fill.fore_color.rgb = ACCENT
    accent.line.fill.background()

    title_box = slide.shapes.add_textbox(Inches(0.72), Inches(0.38), Inches(11.9), Inches(0.85))
    frame = title_box.text_frame
    frame.word_wrap = True
    paragraph = frame.paragraphs[0]
    run = paragraph.add_run()
    run.text = title
    run.font.name = "Segoe UI"
    run.font.size = Pt(28)
    run.font.bold = True
    run.font.color.rgb = INK

    data = CategoryChartData()
    data.categories = labels
    data.add_series("Giá trị", values)
    graphic = slide.shapes.add_chart(
        CHART_TYPES[chart_type], Inches(0.9), Inches(1.45), Inches(11.5), Inches(5.25), data
    )
    chart = graphic.chart
    chart.has_title = False
    chart.font.name = "Segoe UI"
    chart.font.size = Pt(14)
    chart.font.color.rgb = INK
    chart.has_legend = chart_type == "pie"
    if chart_type == "pie":
        chart.legend.position = XL_LEGEND_POSITION.RIGHT
        chart.legend.include_in_layout = False
    plot = chart.plots[0]
    plot.gap_width = 60
    plot.has_data_labels = True
    labels_format = plot.data_labels
    labels_format.number_format = "#,##0.##"
    labels_format.number_format_is_linked = False
    labels_format.font.size = Pt(12)
    labels_format.font.color.rgb = INK
    if chart_type == "pie":
        labels_format.position = XL_LABEL_POSITION.INSIDE_END
        for index, point in enumerate(plot.series[0].points):
            point.format.fill.solid()
            point.format.fill.fore_color.rgb = PIE_COLORS[index % len(PIE_COLORS)]
    else:
        labels_format.position = XL_LABEL_POSITION.OUTSIDE_END
        series = plot.series[0]
        if chart_type == "line":
            series.format.line.color.rgb = ACCENT
            series.format.line.width = Pt(2.5)
        else:
            series.format.fill.solid()
            series.format.fill.fore_color.rgb = ACCENT

    footer = slide.shapes.add_textbox(Inches(0.72), Inches(6.95), Inches(11.9), Inches(0.35))
    footer_frame = footer.text_frame
    footer_frame.word_wrap = True
    footer_run = footer_frame.paragraphs[0].add_run()
    footer_run.text = "DUSN-X · dữ liệu do người dùng nhập"
    footer_run.font.name = "Segoe UI"
    footer_run.font.size = Pt(10)
    footer_run.font.color.rgb = MUTED

    output = BytesIO()
    presentation.save(output)
    return output.getvalue()
